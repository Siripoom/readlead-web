import type { ReactNode } from "react";

export const LEGAL_DOC_IDS = ["tos", "privacy", "writer"] as const;
export type LegalDocId = (typeof LEGAL_DOC_IDS)[number];

export const LEGAL_DOC_LABELS: Record<LegalDocId, string> = {
  tos: "ข้อตกลงการใช้งาน",
  privacy: "นโยบายความเป็นส่วนตัว",
  writer: "ข้อตกลงนักเขียน",
};

export function isLegalDocId(value: unknown): value is LegalDocId {
  return typeof value === "string" && (LEGAL_DOC_IDS as readonly string[]).includes(value);
}

export function parseLegalDoc(value?: string | null): LegalDocId {
  return isLegalDocId(value) ? value : "tos";
}

export function legalDocHref(doc: LegalDocId) {
  return `/legal?doc=${doc}`;
}

export interface LegalSection {
  id: string;
  heading: string;
  body: ReactNode;
}

export interface LegalDocument {
  id: LegalDocId;
  title: string;
  updatedLabel: string;
  sections: LegalSection[];
  contact: ReactNode;
}

function Strong({ children }: { children: ReactNode }) {
  return <b className="text-[#191b22]">{children}</b>;
}

function P({ children }: { children: ReactNode }) {
  return <p className="mb-2.75 text-[#4b5061]">{children}</p>;
}

function List({ children }: { children: ReactNode }) {
  return <ul className="mb-3.5 ml-5.25 mt-1 list-disc text-[#4b5061] [&>li]:mb-1.75">{children}</ul>;
}

function Sub({ children }: { children: ReactNode }) {
  return <h3 className="mb-1.75 mt-5 text-[14.5px] font-extrabold text-[#191b22]">{children}</h3>;
}

